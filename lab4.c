// Напишите функцию поиска минимального элемента в динамическом двухмерном массиве целых чисел

// 1. если выделен сплошняковый кусок памяти {{v1, v2, v3}, {v4, v5, ...}, ...}
int find_min_num1(int* arr, int size1, int size2){
    int min = arr[0];
    for (int i=0; i < size1; i++){
        for (int j=0; j < size2; j++){
            if (*(arr + i*size2 +j) < min){
                min = *(arr + i*size2 + j);
            }
        }
    }
    return min;
}

// 2. если массив создавался как указатели на другие массивы {ptr1, ptr2, ptr3, ...}
int find_min_num2(int** arr, int size1, int size2){
    int min = **arr;
    for (int i=0; i<size1; i++){
        for (int j=0; j < size2; j++){
            if (*(*(arr + i) + j) < min){
                min = *(*(arr + i) + j);
            } 
        }
    }
    return min;
}








