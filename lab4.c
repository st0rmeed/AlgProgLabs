// Для проверки напишите функцию, которая выводит значения всех элементов на экран
int *add_new_element(int *arr, int size, int num){
    // проверим, есть ли элемент в массиве
    for (int i=0; i<size; i++){
        if (arr[i] == num){
            return arr;
        }
    }

    int* new_arr = malloc((size + 1) * sizeof(int));
    for (int i=0; i < size; i++){
        new_arr[i] = arr[i];
    }

    new_arr[size] = num;

    return new_arr;
}

